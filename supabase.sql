create table if not exists public.race_results (
  id bigint generated by default as identity primary key,
  winner text not null,
  distance numeric not null default 0,
  player_one text not null,
  player_two text not null,
  created_at timestamptz not null default now()
);

alter table public.race_results enable row level security;

-- Laboratorio 4: permite que cualquier visitante lea el ranking compartido.
drop policy if exists "Anyone can read race results" on public.race_results;
create policy "Anyone can read race results"
on public.race_results for select
to anon, authenticated
using (true);

-- Laboratorio 4: permite guardar resultados usando sólo la publishable key.
drop policy if exists "Anyone can insert race results" on public.race_results;
create policy "Anyone can insert race results"
on public.race_results for insert
to anon, authenticated
with check (
  length(trim(winner)) between 1 and 40
  and length(trim(player_one)) between 1 and 40
  and length(trim(player_two)) between 1 and 40
  and distance >= 0
);

grant select, insert on public.race_results to anon, authenticated;
grant usage, select on sequence public.race_results_id_seq to anon, authenticated;
